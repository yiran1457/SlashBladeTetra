// ---- shared values (root gradle.properties) ----
fun prop(name: String): String = property(name).toString()

val modId = prop("mod_id")
val modName = prop("mod_name")
// ---- per-node values (versions/<node>/gradle.properties) ----
val tetraFileId = prop("tetra_file_id")
val mutilFileId = prop("mutil_file_id")

// Mod version: <base>-<tetra node>-<suffix>, so each node publishes a coherent version.
val nodeVersion = sc.current.project
val modVersion = "${prop("mod_version_base")}-${nodeVersion}-${prop("mod_version_suffix")}"

version = modVersion
group = prop("mod_group_id")

tasks.withType<Wrapper>().configureEach {
    distributionType = Wrapper.DistributionType.BIN
}

repositories {
    mavenLocal()
}

extensions.configure<BasePluginExtension> {
    archivesName.set(modName)
}

// Mojang ships Java 17 to end users in 1.20.1, so mods should target Java 17.
extensions.configure<JavaPluginExtension> {
    toolchain.languageVersion.set(JavaLanguageVersion.of(21))
}

val sourceSets = extensions.getByType(org.gradle.api.tasks.SourceSetContainer::class.java)
val mainSourceSet = sourceSets.getByName("main")

extensions.configure<LegacyForgeExtension> {
    version = "${prop("minecraft_version")}-${prop("forge_version")}"

    parchment {
        mappingsVersion.set(prop("parchment_mappings_version"))
        minecraftVersion.set(prop("parchment_minecraft_version"))
    }

    // Override MDG's auto-detection: it scans the node's resources srcDirs, which for a
    // non-active node is Stonecutter's generated output and would create an undeclared
    // task dependency from createMinecraftArtifacts on stonecutterGenerate.
    setAccessTransformers(rootProject.file("src/main/resources/META-INF/accesstransformer.cfg"))

    // Default run configurations.
    runs {
        create("client") {
            client()
            systemProperty("forge.enabledGameTestNamespaces", modId)
        }

        create("server") {
            server()
            systemProperty("forge.enabledGameTestNamespaces", modId)
        }

        create("gameTestServer") {
            type.set("gameTestServer")
            systemProperty("forge.enabledGameTestNamespaces", modId)
        }

        create("data") {
            data()
            programArguments.addAll(
                "--mod", modId, "--all",
                "--output", rootProject.file("src/generated/resources/").absolutePath,
                "--existing", rootProject.file("src/main/resources/").absolutePath
            )
        }

        configureEach {
            systemProperty("forge.logging.markers", "REGISTRIES")
            //jvmArguments.add("-XX:+AllowEnhancedClassRedefinition")
            //jvmArguments.add("-XX:HotswapAgent=fatjar")
            logLevel.set(Level.DEBUG)
        }
    }

    mods {
        create(modId) {
            sourceSet(mainSourceSet)
        }
    }
}

// Include resources generated by the data generator (shared path, resolved through the root project).
mainSourceSet.resources.srcDir(rootProject.file("src/generated/resources"))

