// Extends the declared replacement properties in the resources target.
// A missing property is an error. Properties use ${} Groovy notation in the templates.
val generateModMetadata = tasks.register<ProcessResources>("generateModMetadata") {
    val replaceProperties = mapOf(
        "minecraft_version" to prop("minecraft_version"),
        "minecraft_version_range" to prop("minecraft_version_range"),
        "forge_version" to prop("forge_version"),
        "forge_version_range" to prop("forge_version_range"),
        "loader_version_range" to prop("loader_version_range"),
        "mod_id" to modId,
        "mod_name" to modName,
        "mod_license" to prop("mod_license"),
        "mod_version" to modVersion,
        "mod_authors" to prop("mod_authors"),
        "mod_description" to prop("mod_description"),
        // Hard range per node: a bare version string is a soft spec that matches any newer version.
        "tetra_version_range" to prop("tetra_version_range"),
    )
    inputs.properties(replaceProperties)
    expand(replaceProperties)
    from(rootProject.file("src/main/templates"))
    into(layout.buildDirectory.dir("generated/sources/modMetadata"))
}
mainSourceSet.resources.srcDir(generateModMetadata)
extensions.configure<LegacyForgeExtension> { ideSyncTask(generateModMetadata) }

